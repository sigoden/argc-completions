#!/usr/bin/env bash
# scripts/detect-bridge.sh: bash-completion lookup and bridge signature
# detection.

set -euo pipefail
. "$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)/helper.sh"
helper_init

quiet bash "$SCRIPTS/detect-bridge.sh" --help >"$TMP_DIR/help.txt" 2>&1
assert_contains "detect-bridge usage" "$TMP_DIR/help.txt" 'Usage: detect-bridge.sh <root>'

# write_completion <path> <kind>: a reduced copy of the bash completion
# template each framework installs. The weak-* kinds carry only the primary
# marker, to prove the corroborating marker is required.
write_completion() {
    local path="$1" kind="$2"
    case "$kind" in
        click)
            cat >"$path" <<'EOF'
_black_completion() {
    local IFS=$'\n'
    local response
    response=$(env COMP_WORDS="${COMP_WORDS[*]}" COMP_CWORD=$COMP_CWORD _BLACK_COMPLETE=bash_complete $1)
    for completion in $response; do
        IFS=',' read type value <<< "$completion"
        if [[ $type == 'dir' ]]; then
            COMPREPLY=()
            compopt -o dirnames
        elif [[ $type == 'file' ]]; then
            COMPREPLY=()
            compopt -o default
        elif [[ $type == 'plain' ]]; then
            COMPREPLY+=($value)
        fi
    done
    return 0
}
complete -o nosort -F _black_completion black
EOF
            ;;
        typer)
            cat >"$path" <<'EOF'
_fastapi_completion() {
    local IFS=$'\n'
    COMPREPLY=( $( env COMP_WORDS="${COMP_WORDS[*]}" \
                   COMP_CWORD=$COMP_CWORD \
                   _FASTAPI_COMPLETE=complete_bash $1 ) )
    return 0
}
complete -o default -F _fastapi_completion fastapi
EOF
            ;;
        cobra)
            cat >"$path" <<'EOF'
# bash completion V2 for helm                                 -*- shell-script -*-
__helm_get_completion_results() {
    local requestComp
    requestComp="${words[0]} __complete ${args[*]}"
    out=$(eval "${requestComp}" 2>/dev/null)
}
__helm_process_completion_results() {
    local shellCompDirectiveError=1
    local shellCompDirectiveNoSpace=2
    local shellCompDirectiveNoFileComp=4
    if (((directive & shellCompDirectiveNoFileComp) != 0)); then
        :
    fi
}
__start_helm() {
    local cur prev words cword
    _get_comp_words_by_ref -n =: cur prev words cword
    __helm_get_completion_results
    __helm_process_completion_results
}
complete -o default -F __start_helm helm
EOF
            ;;
        argcomplete)
            cat >"$path" <<'EOF'
_python_argcomplete() {
    local IFS=$'\013'
    COMPREPLY=($(IFS="$IFS" \
        COMP_LINE="$COMP_LINE" \
        COMP_POINT="$COMP_POINT" \
        _ARGCOMPLETE_COMP_WORDBREAKS="$COMP_WORDBREAKS" \
        _ARGCOMPLETE=1 \
        _ARGCOMPLETE_SHELL="bash" \
        __python_argcomplete_run $1))
}
complete -o nospace -o default -o bashdefault -F _python_argcomplete pipx
EOF
            ;;
        clap)
            cat >"$path" <<'EOF'
_clap_complete_demo() {
    local IFS=$'\013'
    local _CLAP_COMPLETE_INDEX=${COMP_CWORD}
    local _CLAP_COMPLETE_COMP_TYPE=${COMP_TYPE}
    if compopt +o nospace 2> /dev/null; then
        local _CLAP_COMPLETE_SPACE=false
    else
        local _CLAP_COMPLETE_SPACE=true
    fi
    local words=("${COMP_WORDS[@]}")
    if [[ "${BASH_VERSINFO[0]}" -ge 4 ]]; then
        words[COMP_CWORD]="$2"
    fi
    COMPREPLY=( $( \
        _CLAP_IFS="$IFS" \
        _CLAP_COMPLETE_INDEX="$_CLAP_COMPLETE_INDEX" \
        _CLAP_COMPLETE_COMP_TYPE="$_CLAP_COMPLETE_COMP_TYPE" \
        _CLAP_COMPLETE_SPACE="$_CLAP_COMPLETE_SPACE" \
        COMPLETE="bash" \
        demo -- "${words[@]}" \
    ) )
}
complete -o nospace -o bashdefault -F _clap_complete_demo demo
EOF
            ;;
        urfave)
            cat >"$path" <<'EOF'
# This is a shell completion script auto-generated by https://github.com/urfave/cli for bash.
__demo_build_completion_request() {
    local -a words_before_cursor=("${COMP_WORDS[@]:0:${COMP_CWORD}}")
    local current_word="${COMP_WORDS[COMP_CWORD]}"
    if [[ "${current_word}" == "-"* ]]; then
        printf '%s %s --generate-shell-completion' "${words_before_cursor[*]}" "${current_word}"
    else
        printf '%s --generate-shell-completion' "${words_before_cursor[*]}"
    fi
}
__demo_bash_autocomplete() {
    local opts
    opts="$(__demo_build_completion_request)"
    COMPREPLY=( $(compgen -W "${opts}" -- "${COMP_WORDS[COMP_CWORD]}") )
}
complete -o bashdefault -o default -F __demo_bash_autocomplete demo
EOF
            ;;
        yargs)
            cat >"$path" <<'EOF'
###-begin-demo-completions-###
# yargs command completion script
_demo_yargs_completions()
{
    local cur_word args type_list
    cur_word="${COMP_WORDS[COMP_CWORD]}"
    args=("${COMP_WORDS[@]}")
    mapfile -t type_list < <(demo --get-yargs-completions "${args[@]}")
    mapfile -t COMPREPLY < <(compgen -W "${type_list[*]}" -- "${cur_word}")
    return 0
}
complete -o bashdefault -o default -F _demo_yargs_completions demo
###-end-demo-completions-###
EOF
            ;;
        none)
            cat >"$path" <<'EOF'
_plain() {
    COMPREPLY=()
}
complete -F _plain plain
EOF
            ;;
        weak-click)
            printf '_demo_completion() { env _DEMO_COMPLETE=bash_complete demo; }\n' >"$path"
            ;;
        weak-typer)
            printf '_demo_completion() { env _DEMO_COMPLETE=complete_bash demo; }\n' >"$path"
            ;;
        weak-cobra)
            printf '_demo_completion() { demo __complete ""; }\n' >"$path"
            ;;
        weak-argcomplete)
            printf '_demo_completion() { _ARGCOMPLETE=1 demo; }\n' >"$path"
            ;;
        weak-clap)
            printf '_demo_completion() { local _CLAP_COMPLETE_INDEX=${COMP_CWORD}; }\n' >"$path"
            ;;
        weak-urfave)
            printf '_demo_completion() { demo --generate-shell-completion; }\n' >"$path"
            ;;
        weak-yargs)
            printf '_demo_completion() { demo --get-yargs-completions; }\n' >"$path"
            ;;
    esac
}

# detect_run <out> <args...>: run the detector, capture stdout in <out>, and
# print the exit status. stderr is kept for failure diagnostics.
detect_run() {
    local out="$1"
    shift
    local rc=0
    bash "$SCRIPTS/detect-bridge.sh" "$@" >"$out" 2>"$TMP_DIR/detect.err" || rc=$?
    printf '%s' "$rc"
}

# --- framework signatures --------------------------------------------------

for bridge in click typer cobra argcomplete clap urfave yargs; do
    root="db${bridge}$$"
    file="$TMP_DIR/$root"
    write_completion "$file" "$bridge"
    rc="$(detect_run "$TMP_DIR/out" "$root" --bash-completion "$file")"
    check "detect $bridge exit" test "$rc" -eq 0
    assert_line "detect $bridge output" "$TMP_DIR/out" 1 "$bridge"
    check "bridge template $bridge" test -s "$ROOT_DIR/bridges/$bridge.sh"
done

# One marker alone is not enough evidence.
for kind in weak-click weak-typer weak-cobra weak-argcomplete weak-clap weak-urfave weak-yargs none; do
    root="db${kind}$$"
    file="$TMP_DIR/$root"
    write_completion "$file" "$kind"
    rc="$(detect_run "$TMP_DIR/out" "$root" --bash-completion "$file")"
    check "detect $kind exit" test "$rc" -eq 1
    check "detect $kind prints nothing" test ! -s "$TMP_DIR/out"
done

# --- search directories ----------------------------------------------------

user_root="dbuser$$"
mkdir -p "$TMP_DIR/user/completions"
write_completion "$TMP_DIR/user/completions/$user_root" cobra
rc=0
BASH_COMPLETION_USER_DIR="$TMP_DIR/user" \
    bash "$SCRIPTS/detect-bridge.sh" "$user_root" >"$TMP_DIR/out" 2>/dev/null || rc=$?
check "detect user dir exit" test "$rc" -eq 0
assert_line "detect user dir output" "$TMP_DIR/out" 1 cobra

under_root="dbunder$$"
write_completion "$TMP_DIR/user/completions/_$under_root" argcomplete
rc=0
BASH_COMPLETION_USER_DIR="$TMP_DIR/user" \
    bash "$SCRIPTS/detect-bridge.sh" "$under_root" >"$TMP_DIR/out" 2>/dev/null || rc=$?
check "detect underscore exit" test "$rc" -eq 0
assert_line "detect underscore output" "$TMP_DIR/out" 1 argcomplete

suffix_root="dbsuffix$$"
write_completion "$TMP_DIR/user/completions/$suffix_root.bash" click
rc=0
BASH_COMPLETION_USER_DIR="$TMP_DIR/user" \
    bash "$SCRIPTS/detect-bridge.sh" "$suffix_root" >"$TMP_DIR/out" 2>/dev/null || rc=$?
check "detect .bash suffix exit" test "$rc" -eq 0
assert_line "detect .bash suffix output" "$TMP_DIR/out" 1 click

extra_root="dbextra$$"
mkdir -p "$TMP_DIR/extra"
write_completion "$TMP_DIR/extra/$extra_root" typer
rc="$(detect_run "$TMP_DIR/out" "$extra_root" --dir "$TMP_DIR/extra")"
check "detect --dir exit" test "$rc" -eq 0
assert_line "detect --dir output" "$TMP_DIR/out" 1 typer

# A binary directory from PATH contributes both its share/ and etc/ completion
# directories, which is how Homebrew is found.
path_root="dbpath$$"
path_prefix="$TMP_DIR/path-prefix"
mkdir -p "$path_prefix/bin" "$path_prefix/share/bash-completion/completions"
write_completion "$path_prefix/share/bash-completion/completions/$path_root" click
rc=0
PATH="$path_prefix/bin:$PATH" \
    bash "$SCRIPTS/detect-bridge.sh" "$path_root" >"$TMP_DIR/out" 2>/dev/null || rc=$?
check "detect PATH share dir exit" test "$rc" -eq 0
assert_line "detect PATH share dir output" "$TMP_DIR/out" 1 click

compat_root="dbcompat$$"
mkdir -p "$path_prefix/etc/bash_completion.d"
write_completion "$path_prefix/etc/bash_completion.d/$compat_root" cobra
rc=0
PATH="$path_prefix/bin:$PATH" \
    bash "$SCRIPTS/detect-bridge.sh" "$compat_root" >"$TMP_DIR/out" 2>/dev/null || rc=$?
check "detect PATH compat dir exit" test "$rc" -eq 0
assert_line "detect PATH compat dir output" "$TMP_DIR/out" 1 cobra

brew_root="dbbrew$$"
brew_prefix="$TMP_DIR/brew-prefix"
mkdir -p "$brew_prefix/etc/bash_completion.d"
write_completion "$brew_prefix/etc/bash_completion.d/$brew_root" argcomplete
rc=0
HOMEBREW_PREFIX="$brew_prefix" \
    bash "$SCRIPTS/detect-bridge.sh" "$brew_root" >"$TMP_DIR/out" 2>/dev/null || rc=$?
check "detect HOMEBREW_PREFIX exit" test "$rc" -eq 0
assert_line "detect HOMEBREW_PREFIX output" "$TMP_DIR/out" 1 argcomplete

missing_root="dbmissing$$"
rc="$(detect_run "$TMP_DIR/out" "$missing_root" --dir "$TMP_DIR/extra")"
check "detect missing exit" test "$rc" -eq 1
check "detect missing prints nothing" test ! -s "$TMP_DIR/out"

# --- Homebrew precedence ----------------------------------------------------

# The Homebrew compat dir outranks the distro compat dir.
brew_prio_root="dbbrewprio$$"
brew_prio_prefix="$TMP_DIR/brew-priority"
distro_compat="$TMP_DIR/distro-compat"
mkdir -p "$brew_prio_prefix/etc/bash_completion.d" "$distro_compat"
write_completion "$brew_prio_prefix/etc/bash_completion.d/$brew_prio_root" cobra
write_completion "$distro_compat/$brew_prio_root" argcomplete
rc=0
HOMEBREW_PREFIX="$brew_prio_prefix" BASH_COMPLETION_COMPAT_DIR="$distro_compat" \
    bash "$SCRIPTS/detect-bridge.sh" "$brew_prio_root" >"$TMP_DIR/out" 2>/dev/null || rc=$?
check "detect Homebrew beats distro compat exit" test "$rc" -eq 0
assert_line "detect Homebrew beats distro compat output" "$TMP_DIR/out" 1 cobra

# --- usage errors ----------------------------------------------------------

rc="$(detect_run "$TMP_DIR/out")"
check "detect no root exit" test "$rc" -eq 2

rc="$(detect_run "$TMP_DIR/out" 'bad/root')"
check "detect invalid root exit" test "$rc" -eq 2

rc="$(detect_run "$TMP_DIR/out" "missing$$" --bash-completion "$TMP_DIR/no-such-file")"
check "detect missing override exit" test "$rc" -eq 2

rc="$(detect_run "$TMP_DIR/out" "opt$$" --bash-completion)"
check "detect missing option value exit" test "$rc" -eq 2

rc="$(detect_run "$TMP_DIR/out" "opt$$" --dir)"
check "detect missing --dir value exit" test "$rc" -eq 2

rc="$(detect_run "$TMP_DIR/out" "opt$$" --unknown)"
check "detect unknown option exit" test "$rc" -eq 2

helper_finish
