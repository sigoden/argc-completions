#!/usr/bin/env bash

# Generate an init script for one shell and print the line to add to its rc file.
#
# Usage: ./scripts/init-shell.sh <bash|zsh|fish|powershell|nushell>

set -e

ROOT_DIR="$( cd "$( dirname "${BASH_SOURCE[0]}" )/.." &> /dev/null && pwd -P )"
OUT_DIR="$ROOT_DIR/cache/init-shell"

usage() {
    echo "Usage: $(basename "$0") <bash|zsh|fish|powershell|nushell>" >&2
}

main() {
    if [[ $# -ne 1 ]]; then
        usage
        exit 1
    fi

    local shell="$1"
    case "$shell" in
    bash|zsh|fish|powershell|nushell) ;;
    *)
        usage
        exit 1
        ;;
    esac

    local ext file
    case "$shell" in
    bash|zsh) ext="sh" ;;
    fish) ext="fish" ;;
    powershell) ext="ps1" ;;
    nushell) ext="nu" ;;
    esac
    file="$OUT_DIR/init-$shell.$ext"

    mkdir -p "$OUT_DIR"
    if [[ "$shell" == "nushell" ]]; then
        # Nushell checks sourced files at parse time, so this must exist first.
        touch "$OUT_DIR/argc-completions.nu"
    fi
    _init_script "$shell" > "$file"
    _print_source_command "$shell" "$file"
}

_init_script() {
    local shell="$1" argc_completions_root="$ROOT_DIR" argc_completions_path
    local nushell_tmp="$OUT_DIR/argc-completions.nu"
    local os sep="/" sep2=':'
    os="$(_detect_os)"
    if [[ "$shell" =~ ^(bash|fish|zsh)$ ]]; then
        if [[ "$os" == "windows" ]]; then
            argc_completions_path="$(cygpath -w "$argc_completions_root/completions" | sed 's/\\/\\\\/g')"
            argc_completions_path="$argc_completions_path\\\\$os;$argc_completions_path"
        else
            argc_completions_path="\$ARGC_COMPLETIONS_ROOT/completions/$os:\$ARGC_COMPLETIONS_ROOT/completions"
        fi
    else
        if [[ "$os" == "windows" ]]; then
            argc_completions_root="$(cygpath -w "$argc_completions_root" | sed 's/\\/\\\\/g')"
            nushell_tmp="$(cygpath -w "$nushell_tmp" | sed 's/\\/\\\\/g')"
            sep="\\\\"
            sep2=";"
        fi
    fi

    case "$shell" in
    bash)
        cat <<EOF
# Generated by scripts/init-shell.sh
export ARGC_COMPLETIONS_ROOT="$argc_completions_root"
export ARGC_COMPLETIONS_PATH="$argc_completions_path"
if [ -d "\$ARGC_COMPLETIONS_ROOT/bin" ] && [ -n "\$(command ls -A "\$ARGC_COMPLETIONS_ROOT/bin" 2>/dev/null)" ]; then
    export PATH="\$ARGC_COMPLETIONS_ROOT/bin:\$PATH"
fi
argc_scripts=( \$(ls -p -1 "\$ARGC_COMPLETIONS_ROOT/completions/$os" "\$ARGC_COMPLETIONS_ROOT/completions" 2>/dev/null | sed -n 's/\.sh\$//p') )
source <(argc --argc-completions bash "\${argc_scripts[@]}")
EOF
        ;;
    fish)
        cat <<EOF
# Generated by scripts/init-shell.sh
set -gx ARGC_COMPLETIONS_ROOT "$argc_completions_root"
set -gx ARGC_COMPLETIONS_PATH "$argc_completions_path"
if test -d "\$ARGC_COMPLETIONS_ROOT/bin"; and count (command ls -A "\$ARGC_COMPLETIONS_ROOT/bin" 2>/dev/null) >/dev/null
    fish_add_path "\$ARGC_COMPLETIONS_ROOT/bin"
end
set argc_scripts (ls -p -1 "\$ARGC_COMPLETIONS_ROOT/completions/$os" "\$ARGC_COMPLETIONS_ROOT/completions" 2>/dev/null | sed -n 's/\.sh\$//p')
argc --argc-completions fish \$argc_scripts | source
EOF
        ;;
    nushell)
        local path_var=PATH
        if [[ "${OS:-}" == "Windows_NT" ]]; then
            path_var=Path
        fi
        cat <<EOF
# Generated by scripts/init-shell.sh
\$env.ARGC_COMPLETIONS_ROOT = '$argc_completions_root'
\$env.ARGC_COMPLETIONS_PATH = (\$env.ARGC_COMPLETIONS_ROOT + '${sep}completions${sep}${os}${sep2}' + \$env.ARGC_COMPLETIONS_ROOT + '${sep}completions')
let argc_completions_bin = (\$env.ARGC_COMPLETIONS_ROOT + '${sep}bin')
if (\$argc_completions_bin | path exists) {
    if ((ls \$argc_completions_bin | length) > 0) {
        \$env.$path_var = (\$env.$path_var | prepend \$argc_completions_bin)
    }
}
argc --argc-completions nushell | save -f '$nushell_tmp'
source '$nushell_tmp'
EOF
        ;;
    powershell)
        cat <<EOF
# Generated by scripts/init-shell.sh
# Set-PSReadlineKeyHandler -Key Tab -Function MenuComplete
\$env:ARGC_COMPLETIONS_ROOT = '$argc_completions_root'
\$env:ARGC_COMPLETIONS_PATH = (\$env:ARGC_COMPLETIONS_ROOT + '${sep}completions${sep}${os}${sep2}' + \$env:ARGC_COMPLETIONS_ROOT + '${sep}completions')
\$argc_completions_bin = \$env:ARGC_COMPLETIONS_ROOT + '${sep}bin'
if ((Test-Path -LiteralPath \$argc_completions_bin -PathType Container) -and (@(Get-ChildItem -LiteralPath \$argc_completions_bin -Force -ErrorAction SilentlyContinue).Count -gt 0)) {
    \$env:PATH = \$argc_completions_bin + [IO.Path]::PathSeparator + \$env:PATH
}
\$argc_scripts = ((Get-ChildItem -File -Path (\$env:ARGC_COMPLETIONS_ROOT + '${sep}completions${sep}${os}'),(\$env:ARGC_COMPLETIONS_ROOT + '${sep}completions') -ErrorAction SilentlyContinue) | ForEach-Object { \$_.BaseName })
argc --argc-completions powershell \$argc_scripts | Out-String | Invoke-Expression
EOF
        ;;
    zsh)
        cat <<EOF
# Generated by scripts/init-shell.sh
export ARGC_COMPLETIONS_ROOT="$argc_completions_root"
export ARGC_COMPLETIONS_PATH="$argc_completions_path"
if [ -d "\$ARGC_COMPLETIONS_ROOT/bin" ] && [ -n "\$(command ls -A "\$ARGC_COMPLETIONS_ROOT/bin" 2>/dev/null)" ]; then
    export PATH="\$ARGC_COMPLETIONS_ROOT/bin:\$PATH"
fi
argc_scripts=( \$(ls -p -1 "\$ARGC_COMPLETIONS_ROOT/completions/$os" "\$ARGC_COMPLETIONS_ROOT/completions" 2>/dev/null | sed -n 's/\.sh\$//p') )
source <(argc --argc-completions zsh "\${argc_scripts[@]}")
EOF
        ;;
    esac
}

_print_source_command() {
    local shell="$1" file="$2"
    if [[ "$(_detect_os)" == "windows" && "$shell" =~ ^(powershell|nushell)$ ]]; then
        file="$(cygpath -w "$file")"
    fi
    case "$shell" in
    bash|zsh)
        printf "[ -f '%s' ] && source '%s'\n" "$file" "$file"
        ;;
    fish)
        printf "test -f '%s'; and source '%s'\n" "$file" "$file"
        ;;
    powershell)
        printf "if (Test-Path '%s') { . '%s' }\n" "$file" "$file"
        ;;
    nushell)
        printf "source (if ('%s' | path exists) { '%s' } else { null })\n" "$file" "$file"
        ;;
    esac
}

_detect_os() {
    if [[ "${OS:-}" == "Windows_NT" ]]; then
        echo "windows"
    elif [[ "$(uname)" == "Darwin" ]]; then
        echo "macos"
    else
        echo "linux"
    fi
}

main "$@"
