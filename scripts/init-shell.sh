#!/usr/bin/env bash

# Generate shell integration for argc-completions.
#
# Writes cache/init-shell/init-<shell>.<ext> and prints one line for the
# shell's rc file that sources it.
#
# Usage: ./scripts/init-shell.sh <bash|zsh|fish|powershell|nushell> [name...]
#
# With names, generate completions for those commands only; without names,
# scan ARGC_COMPLETIONS_PATH, and ARGC_SCRIPTS overrides the scan when
# the generated script runs.

set -e

ROOT_DIR="$( cd -P "$( dirname "${BASH_SOURCE[0]}" )/.." &> /dev/null && pwd -P )"
OUT_DIR="$ROOT_DIR/cache/init-shell"
NUSHELL_COMPLETIONS="$OUT_DIR/argc-completions.nu"

usage() {
    echo "Usage: $(basename "$0") <bash|zsh|fish|powershell|nushell> [name...]" >&2
}

main() {
    if [[ $# -lt 1 ]]; then
        usage
        exit 1
    fi

    local shell="$1"
    shift
    case "$shell" in
    bash|zsh|fish|powershell|nushell) ;;
    *)
        usage
        exit 1
        ;;
    esac
    _validate_names "$@" || {
        usage
        exit 1
    }

    local os ext sep file path_var
    os="$(_detect_os)"
    TARGET_OS="$os"
    sep="$(_path_sep "$os")"
    case "$shell" in
    bash|zsh) ext="sh" ;;
    fish) ext="fish" ;;
    powershell) ext="ps1" ;;
    nushell) ext="nu" ;;
    esac
    file="$OUT_DIR/init-$shell.$ext"

    mkdir -p "$OUT_DIR"
    if [[ "$shell" == "nushell" ]]; then
        # Nushell checks sourced files at parse time, so this must exist first.
        : > "$NUSHELL_COMPLETIONS"
    fi

    case "$shell" in
    bash|zsh)
        _script_sh "$shell" \
            "$(_posix_root_expr)" \
            "$(_posix_path_expr "$shell" "$os" "$sep")" \
            "$os" "$sep" "$(_names_posix "$@")" > "$file"
        ;;
    fish)
        _script_fish \
            "$(_posix_root_expr)" \
            "$(_posix_path_expr fish "$os" "$sep")" \
            "$os" "$sep" "$(_names_posix "$@")" > "$file"
        ;;
    powershell)
        _script_powershell \
            "$(_pwsh_root_expr)" \
            "$(_pwsh_path_expr "$os" "$sep")" \
            "$os" "$sep" "$(_names_pwsh "$@")" > "$file"
        ;;
    nushell)
        if [[ "$os" == "windows" ]]; then
            path_var=Path
        else
            path_var=PATH
        fi
        _script_nushell \
            "$(_nu_root_expr)" \
            "$(_nu_path_expr "$os" "$sep")" \
            "$os" "$sep" "$(_names_nu "$@")" "$path_var" > "$file"
        ;;
    esac

    _print_snippet "$shell" "$os" "$ext"
}

# Print one line that sources the generated init script.
_print_snippet() {
    local shell="$1" os="$2" ext="$3" sub expr
    sub="cache/init-shell/init-$shell.$ext"
    case "$shell" in
    bash|zsh)
        expr="$(_posix_file_expr "$sub")"
        printf '[ -f %s ] && source %s\n' "$expr" "$expr"
        ;;
    fish)
        expr="$(_posix_file_expr "$sub")"
        printf 'test -f %s; and source %s\n' "$expr" "$expr"
        ;;
    powershell)
        expr="$(_pwsh_file_expr "$sub")"
        printf 'if (Test-Path -LiteralPath (%s)) { . (%s) }\n' "$expr" "$expr"
        ;;
    nushell)
        expr="$(_nu_file_expr "$sub")"
        printf 'source %s\n' "$expr"
        ;;
    esac
}

# --- generated scripts ------------------------------------------------------

_script_sh() {
    local shell="$1" root_expr="$2" path_expr="$3" os="$4" sep="$5" names="$6"

    printf '# Generated by scripts/init-shell.sh for %s\n' "$shell"
    printf 'export ARGC_COMPLETIONS_ROOT=%s\n' "$root_expr"
    printf 'export ARGC_COMPLETIONS_PATH=%s\n' "$path_expr"
    cat <<'EOF'
if [ -d "$ARGC_COMPLETIONS_ROOT/bin" ] && [ -n "$(command ls -A "$ARGC_COMPLETIONS_ROOT/bin" 2>/dev/null)" ]; then
    export PATH="$ARGC_COMPLETIONS_ROOT/bin:$PATH"
fi
if [ -n "${ARGC_SCRIPTS:-}" ]; then
    argc_scripts=( $(printf '%s\n' "$ARGC_SCRIPTS" | tr ' ' '\n' | awk 'NF') )
EOF

    if [[ -n "$names" ]]; then
        printf 'else\n    argc_scripts=( %s )\n' "$names"
    else
        cat <<'EOF'
else
    argc_scripts=()
    while IFS= read -r _argc_dir; do
        [ -n "$_argc_dir" ] || continue
        [ -d "$_argc_dir" ] || continue
EOF
        if [[ "$os" == "windows" ]]; then
            cat <<'EOF'
        if command -v cygpath >/dev/null 2>&1; then
            _argc_dir="$(cygpath -u "$_argc_dir")"
        fi
EOF
        fi
        cat <<'EOF'
        for _argc_file in "$_argc_dir"/*.sh; do
            [ -f "$_argc_file" ] || continue
            _argc_name=${_argc_file##*/}
            argc_scripts+=("${_argc_name%.sh}")
        done
EOF
        printf "    done < <(printf '%%s\\\\n' \"\$ARGC_COMPLETIONS_PATH\" | tr '%s' '\\\\n')\n" "$sep"
        cat <<'EOF'
    if [ ${#argc_scripts[@]} -gt 0 ]; then
        argc_scripts=( $(printf '%s\n' "${argc_scripts[@]}" | awk '!seen[$0]++') )
    fi
EOF
    fi

    cat <<'EOF'
fi
unset _argc_dir _argc_file _argc_name
EOF
    printf 'source <(argc --argc-completions %s "${argc_scripts[@]}")\n' "$shell"
}

_script_fish() {
    local root_expr="$1" path_expr="$2" os="$3" sep="$4" names="$5"

    printf '# Generated by scripts/init-shell.sh for fish\n'
    printf 'set -gx ARGC_COMPLETIONS_ROOT %s\n' "$root_expr"
    printf 'set -gx ARGC_COMPLETIONS_PATH %s\n' "$path_expr"
    cat <<'EOF'
if test -d "$ARGC_COMPLETIONS_ROOT/bin"; and count (command ls -A "$ARGC_COMPLETIONS_ROOT/bin" 2>/dev/null) >/dev/null
    fish_add_path "$ARGC_COMPLETIONS_ROOT/bin"
end
if set -q ARGC_SCRIPTS; and test -n "$ARGC_SCRIPTS"
    set argc_scripts (string split -n ' ' -- $ARGC_SCRIPTS)
EOF

    if [[ -n "$names" ]]; then
        printf 'else\n    set argc_scripts %s\n' "$names"
    else
        cat <<'EOF'
else
    set argc_scripts
EOF
        printf "    for _argc_dir in (string split '%s' -- \$ARGC_COMPLETIONS_PATH)\n" "$sep"
        cat <<'EOF'
        test -d $_argc_dir; or continue
EOF
        if [[ "$os" == "windows" ]]; then
            cat <<'EOF'
        if command -q cygpath
            set _argc_dir (cygpath -u $_argc_dir)
        end
EOF
        fi
        cat <<'EOF'
        for _argc_file in $_argc_dir/*.sh
            test -f $_argc_file; or continue
            set -a argc_scripts (string replace -r '\.sh$' '' -- (basename $_argc_file))
        end
    end
    if set -q argc_scripts[1]
        set argc_scripts (printf '%s\n' $argc_scripts | awk '!seen[$0]++')
    end
EOF
    fi

    cat <<'EOF'
end
argc --argc-completions fish $argc_scripts | source
EOF
}

_script_powershell() {
    local root_expr="$1" path_expr="$2" os="$3" sep="$4" names="$5" psep

    psep="$(_os_sep "$TARGET_OS")"
    printf '# Generated by scripts/init-shell.sh for powershell\n'
    printf '# Set-PSReadlineKeyHandler -Key Tab -Function MenuComplete\n'
    printf '$env:ARGC_COMPLETIONS_ROOT = %s\n' "$root_expr"
    printf '$env:ARGC_COMPLETIONS_PATH = %s\n' "$path_expr"
    printf '$argc_completions_bin = "$env:ARGC_COMPLETIONS_ROOT%sbin"\n' "$psep"
    cat <<'EOF'
if ((Test-Path -LiteralPath $argc_completions_bin -PathType Container) -and (@(Get-ChildItem -LiteralPath $argc_completions_bin -Force -ErrorAction SilentlyContinue).Count -gt 0)) {
    $env:PATH = $argc_completions_bin + [IO.Path]::PathSeparator + $env:PATH
}
if ($env:ARGC_SCRIPTS) {
    $argc_scripts = @($env:ARGC_SCRIPTS -split '\s+' | Where-Object { $_ })
EOF

    if [[ -n "$names" ]]; then
        printf '} else {\n    $argc_scripts = %s\n}\n' "$names"
    else
        printf "} else {\n    \$argc_scripts = @(\n        (\$env:ARGC_COMPLETIONS_PATH -split '%s') |\n" "$sep"
        cat <<'EOF'
        ForEach-Object {
            if (Test-Path -LiteralPath $_ -PathType Container) {
                Get-ChildItem -LiteralPath $_ -Filter '*.sh' -File -ErrorAction SilentlyContinue |
                    ForEach-Object { $_.BaseName }
            }
        } |
        Select-Object -Unique
    )
}
EOF
    fi

    cat <<'EOF'
argc --argc-completions powershell $argc_scripts | Out-String | Invoke-Expression
EOF
}

_script_nushell() {
    local root_expr="$1" path_expr="$2" os="$3" sep="$4" names="$5" path_var="$6"

    printf '# Generated by scripts/init-shell.sh for nushell\n'
    printf 'const argc_completions_root = %s\n' "$root_expr"
    printf '$env.ARGC_COMPLETIONS_ROOT = $argc_completions_root\n'
    printf '$env.ARGC_COMPLETIONS_PATH = %s\n' "$path_expr"
    cat <<'EOF'
let argc_completions_bin = ($argc_completions_root | path join 'bin')
if (($argc_completions_bin | path exists) and ((ls $argc_completions_bin | length) > 0)) {
EOF
    printf '    $env.%s = ($env.%s | prepend $argc_completions_bin)\n' "$path_var" "$path_var"
    cat <<'EOF'
}
let argc_scripts = if (($env.ARGC_SCRIPTS? | default '') | is-not-empty) {
    $env.ARGC_SCRIPTS | split row ' ' | where {|item| $item != ''}
} else {
EOF

    if [[ -n "$names" ]]; then
        printf '    %s\n' "$names"
    else
        printf '    $env.ARGC_COMPLETIONS_PATH\n'
        printf "    | split row '%s'\n" "$sep"
        cat <<'EOF'
    | each {|dir|
        if ($dir | path exists) {
            ls $dir
            | where {|row| ($row.type == 'file') and ($row.name | str ends-with '.sh')}
            | get name
            | each {|file| $file | path basename | str replace -r '\.sh$' ''}
        } else {
            []
        }
    }
    | flatten
    | uniq
EOF
    fi

    cat <<'EOF'
}
const argc_completions_cache = ($argc_completions_root | path join 'cache' 'init-shell' 'argc-completions.nu')
argc --argc-completions nushell ...$argc_scripts | save -f $argc_completions_cache
source $argc_completions_cache
EOF
}

# --- expressions -----------------------------------------------------------

# Print ROOT_DIR relative to HOME, or "." when ROOT_DIR is HOME itself.
# Returns non-zero when ROOT_DIR is not under HOME.
_home_rel() {
    local home
    home="${HOME:-}"
    [[ -n "$home" ]] || return 1
    home="$( cd -P "$home" 2>/dev/null && pwd -P )" || return 1
    case "$ROOT_DIR" in
    "$home") printf '.' ;;
    "$home"/*) printf '%s' "${ROOT_DIR#"$home"/}" ;;
    *) return 1 ;;
    esac
}

_dq_escape() {
    printf '%s' "$1" | sed -e 's/\\/\\\\/g' -e 's/"/\\"/g' -e 's/\$/\\$/g' -e 's/`/\\`/g'
}

_nu_dquote() {
    printf '"%s"' "$(printf '%s' "$1" | sed -e 's/\\/\\\\/g' -e 's/"/\\"/g')"
}

_pwsh_squote() {
    printf "'%s'" "$(printf '%s' "$1" | sed "s/'/''/g")"
}

_pwsh_descape() {
    printf '%s' "$1" | sed -e 's/`/``/g' -e 's/"/`"/g' -e 's/\$/`$/g'
}

_pwsh_dquote() {
    printf '"%s"' "$(_pwsh_descape "$1")"
}

_os_sep() {
    if [[ "$1" == "windows" ]]; then
        printf '\\'
    else
        printf '/'
    fi
}

_native_rel() {
    if [[ "$TARGET_OS" == "windows" ]]; then
        printf '%s' "$1" | sed 's#/#\\#g'
    else
        printf '%s' "$1"
    fi
}

_native_abs_path() {
    local sub="$1" path="$ROOT_DIR"
    [[ -n "$sub" ]] && path="$ROOT_DIR/$sub"
    if [[ "$TARGET_OS" == "windows" ]] && command -v cygpath >/dev/null 2>&1; then
        cygpath -w "$path"
    else
        printf '%s' "$path"
    fi
}

_nu_home_const_expr() {
    local rel="$1"
    if [[ -n "$rel" ]]; then
        printf '(%s | path expand)' "$(_nu_dquote "~/$rel")"
    else
        printf '(%s | path expand)' "$(_nu_dquote "~")"
    fi
}

_nu_source_expr() {
    local rel="$1"
    case "$rel" in
    '') printf '~' ;;
    *[!A-Za-z0-9._+@/-]*) printf '(%s | path expand)' "$(_nu_dquote "~/$rel")" ;;
    *) printf '~/%s' "$rel" ;;
    esac
}

_posix_root_expr() {
    local rel
    rel="$(_home_rel || true)"
    if [[ "$rel" == "." ]]; then
        printf '"$HOME"'
    elif [[ -n "$rel" ]]; then
        printf '"$HOME/%s"' "$(_dq_escape "$rel")"
    else
        printf '"%s"' "$(_dq_escape "$ROOT_DIR")"
    fi
}

_posix_file_expr() {
    local sub="$1" rel
    rel="$(_home_rel || true)"
    if [[ "$rel" == "." ]]; then
        printf '"$HOME/%s"' "$(_dq_escape "$sub")"
    elif [[ -n "$rel" ]]; then
        printf '"$HOME/%s/%s"' "$(_dq_escape "$rel")" "$(_dq_escape "$sub")"
    else
        printf '"%s/%s"' "$(_dq_escape "$ROOT_DIR")" "$(_dq_escape "$sub")"
    fi
}

_posix_path_expr() {
    local shell="$1" os="$2" sep="$3"
    if [[ "$os" == "windows" ]]; then
        if [[ "$shell" == "fish" ]]; then
            printf "(string join '%s' (cygpath -m \"\$ARGC_COMPLETIONS_ROOT/completions/%s\") (cygpath -m \"\$ARGC_COMPLETIONS_ROOT/completions\"))" "$sep" "$os"
        else
            printf '"$(cygpath -m "$ARGC_COMPLETIONS_ROOT/completions/%s")%s$(cygpath -m "$ARGC_COMPLETIONS_ROOT/completions")"' "$os" "$sep"
        fi
    else
        printf '"$ARGC_COMPLETIONS_ROOT/completions/%s%s$ARGC_COMPLETIONS_ROOT/completions"' "$os" "$sep"
    fi
}

_pwsh_root_expr() {
    local rel sep
    rel="$(_home_rel || true)"
    sep="$(_os_sep "$TARGET_OS")"
    if [[ "$rel" == "." ]]; then
        printf '"$HOME"'
    elif [[ -n "$rel" ]]; then
        printf '"$HOME%s%s"' "$sep" "$(_pwsh_descape "$(_native_rel "$rel")")"
    else
        _pwsh_squote "$(_native_abs_path)"
    fi
}

_pwsh_file_expr() {
    local sub="$1" rel sep path
    rel="$(_home_rel || true)"
    sep="$(_os_sep "$TARGET_OS")"
    if [[ "$rel" == "." ]]; then
        path="$sub"
    elif [[ -n "$rel" ]]; then
        path="$rel/$sub"
    else
        _pwsh_squote "$(_native_abs_path "$sub")"
        return
    fi
    printf '"$HOME%s%s"' "$sep" "$(_pwsh_descape "$(_native_rel "$path")")"
}

_pwsh_path_expr() {
    local os="$1" sep="$2" psep
    psep="$(_os_sep "$TARGET_OS")"
    printf '"$env:ARGC_COMPLETIONS_ROOT%scompletions%s%s%s$env:ARGC_COMPLETIONS_ROOT%scompletions"' "$psep" "$psep" "$os" "$sep" "$psep"
}

_nu_root_expr() {
    local rel
    rel="$(_home_rel || true)"
    if [[ "$rel" == "." ]]; then
        _nu_home_const_expr ""
    elif [[ -n "$rel" ]]; then
        _nu_home_const_expr "$rel"
    else
        _nu_dquote "$(_native_abs_path)"
    fi
}

_nu_file_expr() {
    local sub="$1" rel path
    rel="$(_home_rel || true)"
    if [[ "$rel" == "." ]]; then
        path="$sub"
    elif [[ -n "$rel" ]]; then
        path="$rel/$sub"
    else
        _nu_dquote "$(_native_abs_path "$sub")"
        return
    fi
    _nu_source_expr "$path"
}

_nu_path_expr() {
    local os="$1" sep="$2"
    printf "(\$argc_completions_root | path join 'completions' '%s') + '%s' + (\$argc_completions_root | path join 'completions')" "$os" "$sep"
}

# --- helpers ---------------------------------------------------------------

_validate_names() {
    local name
    for name in "$@"; do
        case "$name" in
        ''|*[!A-Za-z0-9._+@-]*)
            printf '[error] invalid command name: %s\n' "$name" >&2
            return 1
            ;;
        esac
    done
}

_names_posix() {
    local name out=""
    for name in "$@"; do
        out="$out '$name'"
    done
    printf '%s' "${out# }"
}

_names_pwsh() {
    local name first=1 out="@"
    [[ $# -gt 0 ]] || return 0
    for name in "$@"; do
        if [[ "$first" -eq 1 ]]; then
            out="$out('$name'"
            first=0
        else
            out="$out, '$name'"
        fi
    done
    printf '%s)' "$out"
}

_names_nu() {
    local name out=""
    [[ $# -gt 0 ]] || return 0
    for name in "$@"; do
        out="$out '$name'"
    done
    printf '[%s]' "$out"
}

_detect_os() {
    case "$(uname -s 2>/dev/null)" in
    Darwin) echo "macos" ;;
    Linux) echo "linux" ;;
    CYGWIN*|MINGW*|MSYS*|Windows_NT) echo "windows" ;;
    *)
        if [[ "${OS:-}" == "Windows_NT" ]]; then
            echo "windows"
        else
            echo "linux"
        fi
        ;;
    esac
}

_path_sep() {
    if [[ "$1" == "windows" ]]; then
        printf ';'
    else
        printf ':'
    fi
}

main "$@"
